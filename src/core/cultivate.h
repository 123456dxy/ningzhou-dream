// 宁州一梦 · C++ 版 — 修炼速度与配给
//
// 这一层把「修炼有多快」拆成玩家能看懂的几个因子：
//
//     修炼速度 = 功法基础 × 资质乘数 × 悟性乘数 × 境界系数 × 配给系数
//
//   · 功法基础：主修功法决定（每层给多少），这是「你会什么」
//   · 资质乘数：灵根好坏，决定同样的功法你能吸收多少
//   · 悟性乘数：理解力，决定功法发挥出几成
//   · 境界系数：越高境界需要的灵气越多，但基数也大
//   · 配给系数：灵石配给（到处都算）+ 灵气配给（只在洞府算）
//
// 旧版是 `(6 + apt*0.2) * 境界 * 传承 * 功法`，资质是唯一变量，
// 悟性只管参悟，配给完全没有 —— 玩家除了堆资质没别的选择。
#pragma once

#include <string>
#include <vector>

#include "core/model.h"

namespace nz::cultivate {

// ------------------------------------------------------------
// 三个乘数（界面上要如实展示，所以都单独暴露）
// ------------------------------------------------------------
// 资质乘数：以 90 为基准 1.0，每点 ±0.9%，范围 0.5..2.0。
// 用途：将资质转为修炼速度乘数。
// 参与流程：基础修炼速度与拆解展示。
// 使用方式：传角色，以资质九十为一倍基准。
// 返回值：限制在 0.5..2.0 的资质倍率。
double aptMul(const Player& p);
// 悟性乘数：以 37 为基准 1.0，每点 ±0.6%，范围 0.5..2.0。
// 用途：将悟性转为修炼速度乘数。
// 参与流程：基础修炼速度与拆解展示。
// 使用方式：传角色，以悟性三十七为一倍基准。
// 返回值：限制在 0.5..2.0 的悟性倍率。
double insightMul(const Player& p);
// 功法基础：功法、悟道与常驻法器汇总的 artMods.cult；洞府气场另算。
// 用途：计算功法等常驻修炼系数的基础速度。
// 参与流程：基础修炼速度第一项。
// 使用方式：传角色，从 artModsOf 取 cult，缺省保留可修炼基数。
// 返回值：旧十八点基数乘统一修为单位倍率，再乘有效 cult；药效不经过此入口。
double manualBase(const Player& p);
// 境界系数
// 用途：按大境界组读取修炼倍率。
// 参与流程：基础修炼速度与拆解展示。
// 使用方式：传角色，使用既有 GROUP_MUL 表。
// 返回值：当前大境界组的倍率。
double realmMul(const Player& p);

// ------------------------------------------------------------
// 配给
// ------------------------------------------------------------
// 配给档位 0..3
// 用途：给出灵石配给全局最高档位。
// 参与流程：配给设置校验与倍率限制。
// 使用方式：无参数，零表示未配给。
// 返回值：最高档位三。
int maxSupplyLevel();
// 当前洞府档位解锁的配给上限（0/1/2档洞府分别为1/2/3档配给）。
// 用途：计算洞府当前解锁的配给上限。
// 参与流程：配给选项与灵气倍率限制。
// 使用方式：传角色，按洞府 tier 夹在零至二后换算。
// 返回值：一至三档配给上限。
int unlockedSupplyLevel(const Player& p);

// 每月的灵石开销。境界越高越贵。
// 灵气比灵石贵一倍：灵石随处可用，灵气只在洞府生效。
// 用途：计算指定配给档位的每月灵石开销。
// 参与流程：配给预览和月度资源结算。
// 使用方式：传角色、stone/qi 和档位；零档不花费。
// 返回值：按大境界与灵气双倍费用计算的灵石数。
int supplyCost(const Player& p, const std::string& kind, int level);

// 配给带来的乘数（灵石部分，到处都算）
// 用途：计算随处生效的灵石配给倍率。
// 参与流程：最终修炼速度。
// 使用方式：传角色，档位限制到全局配给上限。
// 返回值：一加每档十二个百分点的倍率。
double stoneSupplyMul(const Player& p);
// 灵气部分（只有「在洞府闭关」时才计入）
// 用途：计算在洞府生效的灵气配给倍率。
// 参与流程：最终修炼速度和配给展示。
// 使用方式：传角色，不在洞府或未引灵气时不加成。
// 返回值：有效档位的灵气倍率，否则为一。
double qiSupplyMul(const Player& p);
// 洞府气场只在府内闭关生效，独立于是否付费配给。
// 用途：计算府内洞府气场倍率。
// 参与流程：最终修炼速度的独立洞府收益。
// 使用方式：传角色，需已设置洞府且当前在府内。
// 返回值：洞府 tier 每档加一成，否则为一。
double caveMul(const Player& p);

// 当前是否在洞府
// 用途：判断玩家是否处于已安置洞府的地点。
// 参与流程：灵气配给和洞府气场生效校验。
// 使用方式：传角色，未安置洞府不能当作在府内。
// 返回值：已安府且当前位置相同为真。
bool atCave(const Player& p);
// 灵气配给此刻是否生效（在洞府 + 有档位）
// 用途：检查当前灵气配给能否生效。
// 参与流程：灵气倍率查询。
// 使用方式：传角色，要求府内且灵气档位大于零。
// 返回值：灵气配给此刻有效时为真。
bool qiActive(const Player& p);

// 本次闭关的配给总乘数
// 用途：合并灵石与有效灵气配给倍率。
// 参与流程：最终修炼速度结算。
// 使用方式：传角色，乘上两项配给系数。
// 返回值：配给总乘数。
double supplyMul(const Player& p);

// ------------------------------------------------------------
// 总速度
// ------------------------------------------------------------
// 修炼速度（不含配给），用于界面展示「基础速度」
// 用途：合成功法、资质、悟性、境界、传承和天赋基础速度。
// 参与流程：闭关速度及基础速度展示。
// 使用方式：传角色，配给和洞府气场由 rate 后续乘入。
// 返回值：不含配给与洞府气场的修炼速度。
double baseRate(const Player& p);
// 最终修炼速度（含配给）
// 用途：将基础速度乘以配给和府内气场。
// 参与流程：最终修炼量计算。
// 使用方式：传角色只读状态。
// 返回值：当前条件下最终修炼速度。
double rate(const Player& p);

// 把速度拆成可展示的几项
struct Breakdown {
    double manual = 0;      // 功法基础
    double apt = 1;         // 资质乘数
    double insight = 1;     // 悟性乘数
    double realm = 1;       // 境界系数
    double legacy = 1;      // 传承
    double stone = 1;       // 灵石配给
    double qi = 1;          // 灵气配给
    double cave = 1;        // 洞府气场
    double total = 0;       // 合计
    std::string caveNote;   // 灵气是否生效的说明
};
// 用途：拆解当前修炼速度及府内灵气生效原因。
// 参与流程：修炼页面解释和数值预览。
// 使用方式：传角色，所有因子共用实际速度函数。
// 返回值：各倍率、总速度和洞府说明的 Breakdown 值。
Breakdown breakdown(const Player& p);

// ------------------------------------------------------------
// 其它受资质/悟性影响的
// ------------------------------------------------------------
// 突破成功率的资质/悟性加成（对应 JS 的 insight + apt 项）
// 用途：计算资质和悟性对突破概率的贡献。
// 参与流程：突破成功率汇总。
// 使用方式：传角色；悟性平方根和资质项各自限制收益。
// 返回值：两项合计的概率加成，可含资质负修正。
double breakthroughBonus(const Player& p);
// 修习功法所需天数：悟性越高越快（对应 ecoActionInfo 的 learn 分支）
// 用途：按功法层数、悟性和聪颖天赋计算修习天数。
// 参与流程：学习功法行动报价。
// 使用方式：传角色与要学层数。
// 返回值：至少三天的修习耗时。
int learnDays(const Player& p, int level, int tier = 1);

// ------------------------------------------------------------
// 体魄提供的气血上限
// ------------------------------------------------------------
// 前 8 点每点 +6%（满 +48%）；8 点之后收益降至三分之一，每点 +2%；
// 总加成硬顶在 +72%。
//
// 为什么要软上限：体魄不只是属性点能加，天赋里也叠 ——
// 淬体根骨 +2、筋骨强健 +3、百折不挠 +2、土灵根 +1。
// 属性 8 点再加满天赋能到 15 点以上，纯线性会给出 +90% 气血，
// 比任何功法加成都强，于是「堆体魄」变成唯一解。
// 用途：按软上限计算体魄增加的斗法气血比例。
// 参与流程：斗法开局气血上限与预览。
// 使用方式：传体魄点数，前八点每点百分之六，之后每点百分之二。
// 返回值：不超过百分之七十二的额外气血比例。
double bodyHpBonus(int body);
// 软上限的起点与硬顶（界面上要如实展示，所以暴露出来）
// 用途：提供体魄气血收益的软上限起点。
// 参与流程：体魄收益计算与界面解释。
// 使用方式：无参数，与 bodyHpBonus 使用同一常量。
// 返回值：八点体魄。
int bodySoftCap();
// 用途：提供体魄对气血倍率的硬上限。
// 参与流程：体魄收益计算与界面解释。
// 使用方式：无参数。
// 返回值：最高额外气血比例 0.72。
double bodyHpCap();

// 配给档位的中文名
// 用途：按配给种类和档位生成中文名称。
// 参与流程：配给选项展示。
// 使用方式：传 stone/qi 及档位，零档返回未开启名称。
// 返回值：对应灵石或灵气档位名称。
std::string supplyName(const std::string& kind, int level);
// 配给档位的效果说明
// 用途：解释指定配给档位的速度增益与地点条件。
// 参与流程：配给页面说明。
// 使用方式：传 stone/qi 及档位，沿用实际每档倍率常量。
// 返回值：可展示的配给效果文案。
std::string supplyDesc(const std::string& kind, int level);

} // namespace nz::cultivate
