// 宁州一梦 · C++ 版 — 声望系统
//
// 原版（JS）里「宁州声望」只是结局评分的一项，结局弹窗自己写着
// 「分数只用于比较你自己的不同人生」—— 游戏内没有任何判定读它。
// 也就是说玩家刷了一辈子声望，除了结算时多几分，什么也换不到。
//
// 这里把它做成一套真正的「信誉资本」：
//   名声是你在宁州的招牌，它影响别人怎么对你、愿意给你什么价钱。
//
// 所有加成集中在这个文件里，方便一处调平衡、也方便界面上如实展示。
#pragma once

#include <string>
#include <vector>

#include "core/model.h"

namespace nz::renown {

// 名望档位（给玩家看的身份标签）
struct Tier {
    const char* id;
    const char* name;
    const char* desc;
    int at;              // 达到该档位所需声望
};

// 用途：读取五档声望阈值与说明。
// 参与流程：声望分档及进度查询。
// 使用方式：无参数，使用固定静态表。
// 返回值：Tier 列表常量引用。
const std::vector<Tier>& tiers();

// 当前档位
// 用途：按声望查当前身份档位。
// 参与流程：声望页面和描述。
// 使用方式：传声望，未达下一阈值保持当前档。
// 返回值：静态表中当前 Tier 的引用。
const Tier& tierOf(int renown);
// 距下一档还差多少（已满级返回 -1）
// 用途：计算晋升下一声望档还需的点数。
// 参与流程：声望进度展示。
// 使用方式：传当前声望。
// 返回值：未达下一档的差额；满档为 -1。
int toNextTier(int renown);
// 档位进度 0..1
// 用途：计算当前声望档内进度。
// 参与流程：声望进度条。
// 使用方式：传当前声望，按相邻档阈值归一化。
// 返回值：0..1 的进度，最高档为一。
double tierProgress(int renown);

// ------------------------------------------------------------
// 具体加成
// ------------------------------------------------------------
// 坊市买入折扣（0..0.15）：名声大的人，商家愿意让利
// 用途：计算声望带来的坊市买入折扣。
// 参与流程：商品购买报价。
// 使用方式：传非负口径声望，负值按零处理。
// 返回值：不超过百分之十五的折扣比例。
double buyDiscount(int renown);
// 坊市卖出溢价（0..0.20）
// 用途：计算声望带来的出售溢价。
// 参与流程：坊市收购报价。
// 使用方式：传声望，负值不提供加成。
// 返回值：不超过百分之二十的溢价比例。
double sellBonus(int renown);
// 每月同类货品需求上限（基础 8）
// 用途：计算同类货品月度出售上限。
// 参与流程：坊市需求量校验。
// 使用方式：传当前声望，每二十点增加一件。
// 返回值：八至十四件的月度上限。
int sellLimit(int renown);
// 坊市收购资金上限（基础 400）
// 用途：计算坊市当前角色可享的收购资金额度。
// 参与流程：坊市出售资金限制。
// 使用方式：传声望，每点增加八灵石额度。
// 返回值：四百至两千四百的资金上限。
int marketCashCap(int renown);

// 初见印象：名声在外，陌生人初始就对你有所耳闻（0..25）
// 用途：计算声望影响的初见好感系数。
// 参与流程：首次见礼和 NPC 初始关系。
// 使用方式：传当前声望，每四点折算一点。
// 返回值：零至二十五的初见印象值。
int firstImpression(int renown);

// 藏经阁兑换折扣（0..0.25）
// 用途：计算声望带来的藏经阁兑换折扣。
// 参与流程：宗门传承报价。
// 使用方式：传当前声望，负值按零。
// 返回值：最高百分之二十五的兑换折扣。
double libraryDiscount(int renown);

// 山门差事工钱加成（0..0.30）
// 用途：计算声望对山门差事工钱的加成。
// 参与流程：宗门差事收益报价。
// 使用方式：传声望，不修改俸禄账。
// 返回值：最高百分之三十的工钱比例加成。
double stipendBonus(int renown);

// 宗门入门要求（部分大派看名声）
// 用途：查询特定宗门的入门声望要求。
// 参与流程：宗门考核前置。
// 使用方式：传宗门 ID，星河和离火有额外要求。
// 返回值：两宗为八点，其余为零。
int sectRequirement(const std::string& sectId);
// 拜师要求
// 用途：提供拜师统一声望门槛。
// 参与流程：当面拜师校验。
// 使用方式：无参数。
// 返回值：十点声望。
int masterRequirement();

// 声望增减的说明文案（界面上用）
// 用途：生成当前声望身份与晋档说明。
// 参与流程：声望页面说明。
// 使用方式：传当前声望。
// 返回值：档位描述及距下一档点数的文案。
std::string describe(int renown);
struct Entry {
    std::string tab, sub, location, label;
};
struct Source {
    std::string id, name, gainText;
    std::vector<std::string> conditions;
    std::string limit;
    bool enabled = false;
    std::string reason;
    Entry entry;
};
// 只读目录，列出真实结算来源及当前资格；查看不会推进时间或随机数。
// 用途：列出声望来源及当前可行动资格。
// 参与流程：声望导航目录。
// 使用方式：有 Game 时逐项检查真实条件；无参数时读简明说明。
// 返回值：结构化来源或旧说明列表，不推进时间与 RNG。
std::vector<Source> sources(const Game& g);
// 旧调用方的简明说明。
// 用途：列出声望来源及当前可行动资格。
// 参与流程：声望导航目录。
// 使用方式：有 Game 时逐项检查真实条件；无参数时读简明说明。
// 返回值：结构化来源或旧说明列表，不推进时间与 RNG。
std::vector<std::string> sources();

} // namespace nz::renown
