// 宁州一梦 · C++ 版 — 兽潮
//
// 为什么要这个东西：中后期玩家会陷入「过月—闭关—过月」的空转，
// 没有外部压力，也没有非做不可的事。兽潮给一个全图事件：
//
//   妖潮自险地涌出，波及**所有**地点（不只是你在的那一处）。
//   低境界修士首当其冲 —— NPC 会真的死，你认识的人也会。
//   迎战有厚赏（声望、灵石、材料、大道经验），躲着则错过机缘。
//
// 三条设计约束：
//   1. 全图起效 —— 不是「你所在的地点刷怪」，而是整个世界在死人
//   2. 可致 NPC 死亡 —— 且优先死低境界的，境界高的能扛
//   3. 给成长动力 —— 迎战的收益要明显高于平时的野外悬赏
#pragma once

#include <string>
#include <vector>

#include "core/model.h"

namespace nz::tide {

// ------------------------------------------------------------
// 状态查询
// ------------------------------------------------------------
// 当前兽潮的危险加成（0 表示没有兽潮）
// 用途：读取当前妖潮的野外风险加成。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入const Game& g，按本模块入口调用。
// 返回值：说明所述数值结果；不额外消耗资源。
int dangerBonus(const Game& g);
// 一句话描述当前形势
// 用途：生成当前妖潮状态中文说明。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入const Game& g，按本模块入口调用。
// 返回值：对应文字、ID或失败原因；动作错误接口成功时为空。
std::string statusText(const Game& g);

// ------------------------------------------------------------
// 推进
// ------------------------------------------------------------
// 年度钩子：决定要不要起兽潮
// 用途：推进妖潮年度开启与结束。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入Game& g，按本模块入口调用。
// 返回值：无；完成说明所述写入或展示操作。
void yearTick(Game& g);
// 月度钩子：兽潮蔓延、NPC 伤亡、倒计时
// 用途：结算妖潮月度影响与损失。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入Game& g，按本模块入口调用。
// 返回值：无；完成说明所述写入或展示操作。
void monthTick(Game& g);

// ------------------------------------------------------------
// 玩家迎战
// ------------------------------------------------------------
struct FightResult {
    bool ok = false;
    std::string text;
    std::string error;
    int rewardStones = 0;
    int rewardRenown = 0;
    std::string rewardItem;      // 掉落的材料名
    int killed = 0;              // 这一波杀了多少妖兽
    bool lethal = false;         // 是否已开打（转战斗）
};
// 迎战一波兽潮。severity 越高，对手越强、赏越厚。
// 用途：构造当前妖潮讨伐遭遇与门槛。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入Game& g，按本模块入口调用。
// 返回值：FightResult结果，包含说明所述状态或计算数据。
FightResult fight(Game& g);
// 战后结算（由 battleFinish 的 hunt 分支调用）
// 用途：结算妖潮战斗的胜负收益。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入Game& g, bool won，按本模块入口调用。
// 返回值：无；完成说明所述写入或展示操作。
void tideReward(Game& g, bool won);
// 固守（安全，但没有收益）
// 用途：安排城池避潮并支付成本。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入Game& g，按本模块入口调用。
// 返回值：对应文字、ID或失败原因；动作错误接口成功时为空。
std::string hunkerDown(Game& g);

// ------------------------------------------------------------
// 初始化
// ------------------------------------------------------------
// 用途：补齐旧存档的妖潮状态。
// 参与流程：妖潮开启、讨伐与避潮。
// 使用方式：传入Game& g，按本模块入口调用。
// 返回值：无；完成说明所述写入或展示操作。
void ensureTide(Game& g);

} // namespace nz::tide
